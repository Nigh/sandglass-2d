import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { installMotionFixture } from './motion-fixture.js';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless:true, args:['--no-sandbox'] });
const errors = [];
const base = process.env.BASE_URL || 'http://localhost:5173';
try {
  const page = await browser.newPage({ viewport:{width:390,height:844}, isMobile:true, hasTouch:true, deviceScaleFactor:2 });
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(installMotionFixture);
  await page.goto(base);
  await page.waitForFunction(()=>document.querySelector('#mode').textContent==='随手机倾斜');
  assert.equal(await page.evaluate(()=>window.motionRequests),1,'mobile must request sensors automatically');
  await page.waitForFunction(()=>Number(document.querySelector('canvas').dataset.time)>12);
  await page.screenshot({path:'docs/mobile.png'});
  await page.getByRole('button',{name:'暂停',exact:true}).click();
  await page.waitForTimeout(1000);
  const time = await page.locator('canvas').getAttribute('data-time');
  await page.waitForTimeout(1000); assert.equal(await page.locator('canvas').getAttribute('data-time'),time);
  await page.getByRole('button',{name:'继续',exact:true}).click();
  for(const [width,height] of [[320,568],[768,1024],[1024,768],[1440,900],[844,390]]) {
    await page.setViewportSize({width,height});
    await page.waitForTimeout(100);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    const box = await page.locator('canvas').boundingBox(); assert.ok(box.width>100 && box.height>180);
    const flip = await page.locator('#flip').boundingBox(); assert.ok(flip.x>=0 && flip.x+flip.width<=width && flip.y+flip.height<=height);
  }
  await page.setViewportSize({width:390,height:844});
  await page.locator('#flip').click();
  await page.locator('#settings').click(); assert.ok(await page.locator('dialog').evaluate(e=>e.open));
  await page.selectOption('#palette','rose'); await page.locator('#close').click();
  await page.locator('#immerse').click(); assert.ok(await page.locator('body').evaluate(e=>e.classList.contains('immersed')));
  await page.locator('#leave').click(); assert.ok(!await page.locator('body').evaluate(e=>e.classList.contains('immersed')));
  await page.locator('#motion').click();
  await page.waitForFunction(()=>document.querySelector('#mode').textContent==='随手机倾斜');
  await page.evaluate(()=>{window.motionReading={x:0,y:0,z:9.80665};});
  await page.waitForFunction(()=>document.querySelector('#mode').textContent==='平放 · 壁面摩擦');
  await page.evaluate(()=>{window.motionReading=null;});
  await page.waitForTimeout(2500);assert.equal(await page.locator('#mode').textContent(),'手机读数已中断');
  await page.locator('#motion').click();assert.equal(await page.locator('#mode').textContent(),'手动把玩');
  await page.evaluate(()=>{window.motionPermission='denied';});
  await page.locator('#motion').click();await page.waitForTimeout(100);assert.match(await page.locator('#notice').textContent(),/权限未获允许/);
  const gesture=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  gesture.on('pageerror',e=>errors.push(e.message));
  await gesture.addInitScript(installMotionFixture,{gestureRequired:true});await gesture.goto(base);
  await gesture.waitForFunction(()=>document.querySelector('#mode').textContent==='等待传感器授权');
  await gesture.getByRole('button',{name:/点击授权手机传感器/}).click();
  await gesture.waitForFunction(()=>document.querySelector('#mode').textContent==='随手机倾斜');await gesture.close();
  const desktop=await browser.newPage({viewport:{width:1440,height:900}});desktop.on('pageerror',e=>errors.push(e.message));
  await desktop.goto(base);await desktop.waitForFunction(()=>Number(document.querySelector('canvas').dataset.time)>12);
  assert.equal(await desktop.locator('#mode').textContent(),'手动把玩');await desktop.screenshot({path:'docs/desktop.png'});await desktop.close();
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: mobile, 5 viewports, pause, flip, settings, immersion, automatic sensors, gesture permission, flat-phone friction, readings/staleness.');
} finally { await browser.close(); }
